#!/bin/bash
# Writes Soredemo/App/BuildProvenance.swift — `stamp` with this tree's commit and the time, or
# `placeholder` with the committed baseline. Used by build-app-for-verification.sh and
# build-release.sh, which stamp before compiling and put the placeholder back on exit.
#
# **Why the placeholder goes back, every time.** The stamped file used to be left in the tree,
# and it was committed with unrelated work more than forty times — so the committed baseline read
# "5ee4041-dirty", a plausible hash, and a plain Xcode build reported it as though it were this
# build's. A measurement has no safe default: the baseline must read as obviously not a reading.
# `appProvenanceIsCommittedAsThePlaceholder` fails if a stamped copy is ever in the tree.
set -euo pipefail
cd "$(dirname "$0")/.."

FILE=Soredemo/App/BuildProvenance.swift

write() {
  cat > "$FILE" <<SWIFT
// GENERATED by scripts/build-provenance.sh — do not hand-edit. Committed as the placeholder;
// stamped only for the length of a build run through build-app-for-verification.sh or
// build-release.sh, which put the placeholder back when they exit.

/// Which build produced THIS binary — baked in at compile time, not read from \`git\` at launch,
/// which would report the checkout's state now rather than the tree that was compiled.
///
/// The placeholder is what a plain \`xcodebuild\` or Xcode's Cmd+B produces, since neither runs
/// the script. It reads as obviously fake so an identity block built from it cannot be mistaken
/// for a reading (AGENTS.md: failure lands outside the value's legal range).
enum BuildProvenance {
    static let builtAt = "$1"
    static let commit = "$2"
}
SWIFT
}

case "${1:-}" in
  stamp)
    COMMIT=$(git rev-parse --short HEAD)
    # Excluding this file: stamping it is what makes the tree look dirty to the next run.
    if ! git diff --quiet -- . ":!$FILE" || ! git diff --cached --quiet -- . ":!$FILE"; then
      COMMIT="${COMMIT}-dirty"
    fi
    BUILT_AT=$(date -u "+%Y-%m-%d %H:%M:%S UTC")
    write "$BUILT_AT" "$COMMIT"
    echo "Baked provenance: commit=${COMMIT} builtAt=${BUILT_AT}"
    ;;
  placeholder)
    UNBUILT="UNBUILT — not built via scripts/build-app-for-verification.sh or build-release.sh"
    write "$UNBUILT" "$UNBUILT"
    ;;
  *)
    echo "usage: $0 stamp|placeholder" >&2
    exit 2
    ;;
esac
